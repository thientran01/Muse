// ============================================================
//  BUILD THE OVERLAY'S INJECTABLE STYLESHEET
// ------------------------------------------------------------
//  Compiles the Muse overlay's full CSS — Tailwind base (preflight) + components
//  + utilities, scanned from src/muse, plus the muse.css design tokens — into a
//  single committed TS string module: src/muse/generated/overlayCss.ts.
//
//  Why a string module: the overlay renders inside a Shadow DOM root, which does
//  NOT inherit the host document's stylesheets. So the CSS is injected into the
//  shadow root at runtime. Shipping it as a JS string makes it bundler-agnostic
//  (Vite / Next / webpack) and means a HOST never runs Tailwind for the overlay —
//  which is exactly what broke the Tailwind v4 portfolio (unscoped utility
//  collision). Inside the shadow boundary it cannot touch the host, and preflight
//  is now SAFE to include (it normalizes the overlay's own elements; without it
//  shadow elements fall back to UA styles).
//
//  Comments in src/muse are stripped before Tailwind scans them, so example class
//  strings in code comments (e.g. font-[var(...)]) are never compiled into invalid
//  CSS.
//
//  Run: npm run build:overlay-css   (regenerate whenever overlay classes change)
// ============================================================
import fs from 'node:fs'
import path from 'node:path'
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import autoprefixer from 'autoprefixer'

const root = process.cwd()
const museCssPath = path.join(root, 'src/muse/muse.css')
const outDir = path.join(root, 'src/muse/generated')
const outPath = path.join(outDir, 'overlayCss.ts')

const museCss = fs.readFileSync(museCssPath, 'utf8')
const baseConfig = (await import('file://' + path.join(root, 'tailwind.config.js'))).default

// Strip comments so class-like example strings in code comments aren't scanned as
// real utilities. Scan-only transform: it can corrupt string literals (e.g. URLs),
// which is harmless here since we only use the result for class extraction.
const stripComments = (src) =>
  src
    .replace(/\/\*[\s\S]*?\*\//g, ' ') // block comments
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1') // line comments (skip ://, e.g. URLs)

const config = {
  ...baseConfig,
  content: {
    files: ['./src/muse/**/*.{ts,tsx}'],
    transform: { DEFAULT: stripComments },
  },
}

const input = `@tailwind base;\n@tailwind components;\n@tailwind utilities;\n\n${museCss}`

const result = await postcss([tailwindcss(config), autoprefixer]).process(input, {
  from: undefined,
})

const css = result.css

fs.mkdirSync(outDir, { recursive: true })
const banner =
  '// AUTO-GENERATED by scripts/build-overlay-css.mjs — DO NOT EDIT.\n' +
  '// The Muse overlay stylesheet, injected into the overlay Shadow DOM root so it\n' +
  '// is fully isolated from the host. Regenerate: npm run build:overlay-css\n' +
  '/* eslint-disable */\n'
fs.writeFileSync(outPath, `${banner}export const OVERLAY_CSS = ${JSON.stringify(css)}\n`)

console.log(`[overlay-css] wrote ${path.relative(root, outPath)} (${(css.length / 1024).toFixed(1)} KB)`)
